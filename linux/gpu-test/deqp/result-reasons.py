#!/usr/bin/env python3
"""Inventory every non-Pass result, preserving the CTS reason and case names.

Accepts archived results-*.txt files; prints Markdown or --json. The report
identifies observed skip conditions, not proven hardware limitations.
"""

import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import re


def inventory(path):
    raw = path.read_bytes()
    statuses = Counter()
    groups = defaultdict(list)
    seen = set()
    for number, line in enumerate(raw.decode().splitlines(), 1):
        match = re.fullmatch(r"(\S+) (\w+) @uptime=\S+ \((.*)\)", line)
        if not match:
            raise ValueError(f"{path}:{number}: malformed result")
        case, status, reason = match.groups()
        if case in seen:
            raise ValueError(f"{path}:{number}: duplicate case {case}")
        seen.add(case)
        statuses[status] += 1
        if status != "Pass":
            # Split generic messages by test family without guessing their cause.
            family = ".".join(case.split(".")[:4])
            groups[status, reason, family].append(case)
    return dict(
        path=str(path),
        sha256=hashlib.sha256(raw).hexdigest(),
        total=len(seen),
        statuses=dict(sorted(statuses.items())),
        groups=[dict(status=s, reason=r, family=f, count=len(c), cases=c)
                for (s, r, f), c in sorted(groups.items())],
    )


def cell(text):
    return text.replace("|", "\\|").replace("`", "'")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true", help="include every assigned case name")
    parser.add_argument("results", nargs="+", type=Path)
    args = parser.parse_args()
    reports = [inventory(path) for path in args.results]
    if args.json:
        print(json.dumps(reports, indent=2))
        return
    print("# Archived CTS result reasons\n")
    print("Generated by `linux/gpu-test/deqp/result-reasons.py`. Each non-Pass case")
    print("appears in exactly one group. Reasons are CTS observations; a skip does")
    print("not establish a hardware limit. `--json` includes every case assignment.\n")
    for index, report in enumerate(reports):
        if index:
            print()
        print(f"## {report['path']}\n")
        print(f"SHA256: `{report['sha256']}`\n")
        print(f"{report['total']} cases: " + ", ".join(
            f"{s} {n}" for s, n in report["statuses"].items()) + ".\n")
        print("| Status | Count | Family | Exact CTS reason |")
        print("| --- | ---: | --- | --- |")
        for group in report["groups"]:
            print(f"| {group['status']} | {group['count']} | "
                  f"`{cell(group['family'])}` | {cell(group['reason'])} |")


if __name__ == "__main__":
    main()
